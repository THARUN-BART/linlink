  void _handleScannedData(BuildContext context, String payload) {
    final cameraBloc = context.read<CameraBloc>();
    final target = PairingTarget.tryParse(payload);

    if (target == null) {
      showDialog(
        context: context,
        barrierDismissible: false,
        builder: (dialogCtx) => AlertDialog(
          backgroundColor: LinLinkColors.surfaceContainer,
          title: const Row(
            children: [
              Icon(Icons.warning_amber_rounded, color: LinLinkColors.warning),
              SizedBox(width: 8),
              Text('Unrecognized QR'),
            ],
          ),
          content: Text(
            'The scanned text is not a valid LinLink pairing payload:\n"$payload"\n\n'
            'Please run `linlink pair` in your Linux terminal to generate a valid code.',
            style: const TextStyle(color: LinLinkColors.onSurfaceVariant),
          ),
          actions: [
            TextButton(
              onPressed: () {
                Navigator.of(dialogCtx).pop();
                _showManualEntryDialog(context);
              },
              child: const Text('Enter Manually'),
            ),
            FilledButton(
              onPressed: () {
                Navigator.of(dialogCtx).pop();
                cameraBloc.add(const CameraResetScanRequested());
              },
              child: const Text('Scan Again'),
            ),
          ],
        ),
      );
      return;
    }

    // Detect P2P file transfer QR (mode=p2p)
    final isP2P = payload.contains('mode=p2p');
    if (isP2P) {
      _startP2PReceive(context, target);
      return;
    }

    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (dialogCtx) => _PairingConfirmDialog(
        target: target,
        onSuccess: (companion) {
          Navigator.of(dialogCtx).pop();
          Navigator.of(context).pop(companion);
        },
        onCancel: () {
          Navigator.of(dialogCtx).pop();
          cameraBloc.add(const CameraResetScanRequested());
        },
      ),
    );
  }

  /// P2P receive flow: connect to sender, list queued files, and download them all.
  void _startP2PReceive(BuildContext context, PairingTarget target) {
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (dialogCtx) => _P2PReceiveDialog(
        target: target,
        onComplete: (int count) {
          Navigator.of(dialogCtx).pop();
          Navigator.of(context).pop(); // Return to home
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              backgroundColor: LinLinkColors.secondaryContainer,
              duration: const Duration(seconds: 4),
              content: Row(
                children: [
                  const Icon(Icons.download_done, color: LinLinkColors.secondary),
                  const SizedBox(width: 8),
                  Expanded(
                    child: Text(
                      '📥 Received $count file${count > 1 ? 's' : ''}\nSaved in Downloads/LinLink',
                      style: const TextStyle(fontWeight: FontWeight.w600, fontSize: 12),
                    ),
                  ),
                ],
              ),
            ),
          );
        },
        onCancel: () {
          Navigator.of(dialogCtx).pop();
          context.read<CameraBloc>().add(const CameraResetScanRequested());
        },
      ),
    );
  }

  void _showManualEntryDialog(BuildContext context) {
    final hostController = TextEditingController();
    final portController = TextEditingController(text: '7878');
    final tokenController = TextEditingController();
    final nameController = TextEditingController(text: 'Android Phone');

    showDialog(
      context: context,
      builder: (dialogCtx) => AlertDialog(
        backgroundColor: LinLinkColors.surfaceContainer,
        title: const Row(
          children: [
            Icon(Icons.lan_outlined, color: LinLinkColors.primary),
            SizedBox(width: 10),
            Text('Manual Pairing'),
          ],
        ),
        content: SingleChildScrollView(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const Text(
                'Enter the IP and session token printed by `linlink pair` on your Linux host:',
                style: TextStyle(fontSize: 12, color: LinLinkColors.onSurfaceVariant),
              ),
              const SizedBox(height: 14),
              TextField(
                controller: hostController,
                decoration: const InputDecoration(
                  labelText: 'Linux IP / Host (or full URL)',
                  hintText: '192.168.1.50 or 10.0.0.5',
                ),
              ),
              const SizedBox(height: 10),
              TextField(
                controller: portController,
                keyboardType: TextInputType.number,
                decoration: const InputDecoration(
                  labelText: 'Port',
                  hintText: '7878',
                ),
              ),
              const SizedBox(height: 10),
              TextField(
                controller: tokenController,
                decoration: const InputDecoration(
                  labelText: 'Session Token (or full URL)',
                  hintText: 'e.g. 31327e36 or linlink://...',
                ),
              ),
              const SizedBox(height: 10),
              TextField(
                controller: nameController,
                decoration: const InputDecoration(
                  labelText: 'Device Name (shown on Linux)',
                  hintText: 'Pixel 8',
                ),
              ),
            ],
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(dialogCtx).pop(),
            child: const Text('Cancel'),
          ),
          FilledButton(
            onPressed: () {
              final rawHost = hostController.text.trim();
              final rawToken = tokenController.text.trim();
              final targetFromToken = PairingTarget.tryParse(rawToken);
              final targetFromHost = PairingTarget.tryParse(rawHost);

              final effectiveTarget = targetFromToken ??
                  targetFromHost ??
                  PairingTarget(
                    host: rawHost,
                    port: int.tryParse(portController.text.trim()) ?? 7878,
                    token: rawToken,
                  );

              if (effectiveTarget.token.isEmpty || effectiveTarget.host.isEmpty) {
                ScaffoldMessenger.of(context).showSnackBar(
                  const SnackBar(content: Text('Please enter host and token (or paste URL).')),
                );
                return;
              }

              Navigator.of(dialogCtx).pop();

              showDialog(
                context: context,
                barrierDismissible: false,
                builder: (confirmCtx) => _PairingConfirmDialog(
                  target: effectiveTarget,
                  onSuccess: (companion) {
                    Navigator.of(confirmCtx).pop();
                    Navigator.of(context).pop(companion);
                  },
                  onCancel: () => Navigator.of(confirmCtx).pop(),
                ),
              );
            },
            child: const Text('Proceed'),
          ),
        ],
      ),
    );
  }
}

