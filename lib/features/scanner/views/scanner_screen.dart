                    ),
                  ],
                ),
              ),
            ],
          ],
        ),
      ),
      actions: [
        if (!_isLinking) ...[
          TextButton(
            onPressed: widget.onCancel,
            child: const Text('Cancel'),
          ),
          FilledButton.icon(
            icon: const Icon(Icons.link, size: 18),
            label: const Text('Link Now'),
            onPressed: _startPairing,
          ),
        ],
      ],
    );
  }
