class _PairingConfirmDialog extends StatefulWidget {
  final PairingTarget target;
  final ValueChanged<PairedCompanion> onSuccess;
  final VoidCallback onCancel;

  const _PairingConfirmDialog({
    required this.target,
    required this.onSuccess,
    required this.onCancel,
  });

  @override
  State<_PairingConfirmDialog> createState() => _PairingConfirmDialogState();
}

class _PairingConfirmDialogState extends State<_PairingConfirmDialog> {
  late final TextEditingController _nameController;
  bool _isLinking = false;
  String? _errorMessage;

  @override
  void initState() {
    super.initState();
    String defaultName = 'Android Phone';
    if (Platform.isLinux) {
      defaultName = 'Linux Client';
    } else if (Platform.isMacOS) {
      defaultName = 'Mac Client';
    } else if (Platform.isWindows) {
      defaultName = 'Windows Client';
    } else if (Platform.isIOS) {
      defaultName = 'iPhone';
    }
    _nameController = TextEditingController(text: defaultName);
  }

  @override
  void dispose() {
    _nameController.dispose();
    super.dispose();
  }

  Future<void> _startPairing() async {
    final name =
        _nameController.text.trim().isEmpty ? 'Android Device' : _nameController.text.trim();

    setState(() {
      _isLinking = true;
      _errorMessage = null;
    });

    try {
      final companion = await PairingService.pair(
        target: widget.target,
        deviceName: name,
      );
      if (mounted) {
        widget.onSuccess(companion);
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _isLinking = false;
          _errorMessage = e.toString().replaceFirst('Exception: ', '');
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return AlertDialog(
      backgroundColor: LinLinkColors.surfaceContainer,
      title: const Row(
        children: [
          Icon(Icons.phonelink_setup, color: LinLinkColors.primary),
          SizedBox(width: 10),
          Text('Confirm Connection'),
        ],
      ),
      content: SingleChildScrollView(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const Text(
              'Linux Companion Target:',
              style: TextStyle(
                color: LinLinkColors.onSurfaceVariant,
                fontSize: 12,
                fontWeight: FontWeight.w500,
              ),
            ),
            const SizedBox(height: 8),
            Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: LinLinkColors.surfaceContainerLow,
                borderRadius: BorderRadius.circular(10),
                border: Border.all(color: LinLinkColors.outlineVariant),
              ),
              child: Row(
                children: [
                  Container(
                    width: 36,
                    height: 36,
                    decoration: BoxDecoration(
                      color: LinLinkColors.surfaceContainerHigh,
                      borderRadius: BorderRadius.circular(8),
                    ),
                    child: const Icon(
                      Icons.desktop_windows,
                      size: 20,
                      color: LinLinkColors.primary,
                    ),
                  ),
                  const SizedBox(width: 12),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(
                          '${widget.target.host}:${widget.target.port}',
                          style: const TextStyle(
                            fontWeight: FontWeight.w600,
                            fontSize: 13,
                            fontFamily: 'monospace',
                            color: LinLinkColors.onSurface,
                          ),
                        ),
                        const SizedBox(height: 2),
                        Text(
                          'Token: ${widget.target.token}',
                          style: const TextStyle(
                            color: LinLinkColors.onSurfaceVariant,
